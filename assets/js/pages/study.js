function searchable(items) {
  const q = el("input", { class: "input", type: "search", placeholder: "검색 (예: 도화, 편재, 입춘)" });
  const box = el("div", { class: "st-list" });
  const paint = () => { clear(box); const v = q.value.trim(); items.filter((it) => !v || it.text.includes(v)).forEach((it) => box.append(it.node)); };
  q.addEventListener("input", paint); paint();
  return [q, box];
}

