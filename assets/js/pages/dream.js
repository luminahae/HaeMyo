function findScenes(q) {
  const out = [];
  for (const sc of SCENES) {
    const m = sc.rx.exec(q);
    if (!m) continue;
    if (sc.not && sc.not.test(q) && sc.id === "kill") continue;
    out.push({ ...sc, pos: m.index });
  }
  // 'selfdie'와 'kill'이 둘 다 잡히면 문장 앞쪽 것을 우선
  return out.sort((a, b) => a.pos - b.pos);
}
