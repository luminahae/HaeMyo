export function termOf(text) {
  const n = norm(text);
  // '· 신궁'처럼 칸 이름으로 쓰인 지지궁 (身宮과 구분)
  if (/^\s*·/.test(text || "") && n === "신궁") return "신궁(申)";
  // 정유·병인 처럼 한글로만 쓴 간지 (짧은 글자 단독일 때만)
  const raw = (text || "").trim().replace(/\s*·.*$/, "");
  if (/^[가-힣]{2}$/.test(raw) && KS.includes(raw[0]) && KB.includes(raw[1]) && ((KS.indexOf(raw[0]) % 2) === (KB.indexOf(raw[1]) % 2))) {
    const h = HS[KS.indexOf(raw[0])] + HB[KB.indexOf(raw[1])];
    if (!TERMS[h]) TERMS[h] = `간지 ${h}(${raw}) — 60갑자의 하나. 위는 ${TERMS[h[0]]} / 아래는 ${TERMS[h[1]]}`;
    return h;
  }
  // 甲(갑) / 辛巳(신사) — 천간·지지 한자
  const hm = (text || "").trim().match(/^([甲乙丙丁戊己庚辛壬癸子丑寅卯辰巳午未申酉戌亥]{1,2})(\(|$)/);
  if (hm) {
    const cs = [...hm[1]];
    if (cs.length === 1 && TERMS[cs[0]]) return cs[0];
    if (cs.length === 2 && TERMS[cs[0]] && TERMS[cs[1]]) { const k = hm[1]; if (!TERMS[k]) TERMS[k] = `간지 ${k} — 60갑자의 하나. 위는 ${TERMS[cs[0]]} / 아래는 ${TERMS[cs[1]]}`; return k; }
  }
  if (!n || n.length > 8 || SKIP_SHORT.has(n)) return null;
  if (TERMS[n]) return n;
  const m = n.match(/^([가-힣]+)\(.+\)$/); // 庚(경) 같은 병기는 제외, '정관(正官)' 형태
  if (m && TERMS[m[1]]) return m[1];
  return null;
}

const SEL = "span,b,em,strong,small,td,th,dt,dd,summary";
function mark(node) {
  if (!node || node.nodeType !== 1) return;
  const els = node.matches(SEL) ? [node, ...node.querySelectorAll(SEL)] : [...node.querySelectorAll(SEL)];
  for (const e of els) {
    if (e.dataset.term || e.children.length || e.closest("input,textarea,select,[data-noterm],.term-tip")) continue;
    const t = termOf(e.textContent);
    if (t) e.dataset.term = t;
  }
}

let bubble = null, current = null, hideTimer = null, shownAt = 0, shownY = 0;
